#!/usr/bin/env node
// Builds the brand guide:
//  1. writes the contrast table (from tokens.json, via contrast.mjs) into GUIDE.md between markers;
//  2. renders GUIDE.md to brand/guide.html — ONE self-contained, printable file (inline CSS, inline
//     SVG logos and icons, the Arabic font embedded as a data: URI, no network requests) — and adds
//     visual specimens (logo, colour swatches, type scale, icons) under their sections.
//
//   node brand/scripts/build-guide.mjs          (rewrite both files)
//   node brand/scripts/build-guide.mjs --check  (exit 1 if either file is out of date)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { checkTokens } from "./contrast.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const brand = resolve(here, "..");
const repo = resolve(brand, "..");
const read = (p) => readFileSync(join(brand, p), "utf8");
const tokens = JSON.parse(read("tokens.json"));
const C = Object.fromEntries(Object.entries(tokens.color).map(([k, v]) => [k, v.$value]));

// ---------------------------------------------------------------- 1. contrast table in GUIDE.md
function contrastTable() {
  const rows = checkTokens(tokens);
  const lines = [
    "| Text / element | On | Ratio | Needs | Use |",
    "|---|---|---|---|---|",
    ...rows.map((r) => `| ${r.fg} \`${r.fgHex}\` | ${r.bg} \`${r.bgHex}\` | ${(Math.floor(r.ratio * 100) / 100).toFixed(2)} | ${r.min} | ${r.use} |`),
  ];
  return `<!-- contrast:start -->\n**Contrast table** (generated by \`node brand/scripts/build-guide.mjs\` from \`tokens.json\`; ${rows.filter((r) => r.pass).length}/${rows.length} pass):\n\n${lines.join("\n")}\n<!-- contrast:end -->`;
}

function guideMd() {
  const md = read("GUIDE.md");
  return md.replace(/<!-- contrast:start -->[\s\S]*?<!-- contrast:end -->/, contrastTable());
}

// ---------------------------------------------------------------- 2. tiny Markdown renderer
// Supports exactly what GUIDE.md uses: #/##/### headings, paragraphs, tables, - lists, ---, **bold**,
// *em*, `code`, [links](...), HTML comments. Arabic runs get lang="ar" for the embedded font.
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const AR = /[؀-ۿ]/;
const LATIN = /[A-Za-z]/;
function inline(s) {
  let h = esc(s)
    .replace(/`([^`]+)`/g, "<code>$1</code>")
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
    .replace(/(^|[\s(])\*([^*\s][^*]*)\*/g, "$1<em>$2</em>")
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, (_, t, href) => (/^https?:/.test(href) ? `<a href="${href}">${t}</a>` : `${t} <span class="path">(${href})</span>`));
  if (AR.test(s) && LATIN.test(s.replace(/<[^>]+>/g, ""))) {
    // mixed: isolate each Arabic run
    h = h.replace(/([؀-ۿ][؀-ۿ\s،؟…!.«»0-9-]*[؀-ۿ.…؟!])/g, '<bdi lang="ar" dir="rtl">$1</bdi>');
  }
  return h;
}
const cellAttrs = (s) => (AR.test(s) && !LATIN.test(s) ? ' lang="ar" dir="rtl"' : "");

function render(md, inserts) {
  const out = [];
  const lines = md.split("\n");
  let i = 0;
  let para = [];
  const flush = () => {
    if (para.length) out.push(`<p${cellAttrs(para.join(" "))}>${inline(para.join(" "))}</p>`);
    para = [];
  };
  while (i < lines.length) {
    const l = lines[i];
    if (/^<!--.*-->$/.test(l.trim())) { flush(); i++; continue; }
    let m;
    if ((m = /^(#{1,3}) (.*)$/.exec(l))) {
      flush();
      const n = m[1].length;
      const id = m[2].toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
      out.push(`<h${n} id="${id}">${inline(m[2])}</h${n}>`);
      if (inserts[m[2]]) out.push(inserts[m[2]]);
      i++;
      continue;
    }
    if (l.trim() === "---") { flush(); i++; continue; } // h2 already draws the divider
    if (l.startsWith("|")) {
      flush();
      const rows = [];
      while (i < lines.length && lines[i].startsWith("|")) rows.push(lines[i++]);
      const cells = (r) => r.slice(1, -1).split(" | ").map((c) => c.trim().replace(/^\|\s*|\s*\|$/g, ""));
      const [head, , ...body] = rows;
      out.push(
        `<table><thead><tr>${cells(head).map((c) => `<th${cellAttrs(c)}>${inline(c)}</th>`).join("")}</tr></thead><tbody>` +
          body.map((r) => `<tr>${cells(r).map((c) => `<td${cellAttrs(c)}>${swatchify(inline(c))}</td>`).join("")}</tr>`).join("") +
          "</tbody></table>",
      );
      continue;
    }
    if (/^- /.test(l)) {
      flush();
      const items = [];
      while (i < lines.length && /^(- |  \S)/.test(lines[i])) {
        if (lines[i].startsWith("- ")) items.push(lines[i].slice(2));
        else items[items.length - 1] += " " + lines[i].trim();
        i++;
      }
      out.push(`<ul>${items.map((it) => `<li>${inline(it)}</li>`).join("")}</ul>`);
      continue;
    }
    if (l.trim() === "") { flush(); i++; continue; }
    para.push(l.trim());
    i++;
  }
  flush();
  return out.join("\n");
}
// colour chips next to hex codes in tables
const swatchify = (h) => h.replace(/(?:<code>)?(#[0-9a-f]{6})(?:<\/code>)?/gi, (m, hex) => `<span class="chip" style="background:${hex}"></span>${m}`);

// ---------------------------------------------------------------- 3. specimens
const svgBody = (s) => s.replace(/<title>.*?<\/title>/, "");
const logo = (f) => svgBody(read(`logo/${f}`));

function logoSpecimen() {
  return `<div class="spec logos">
  <figure class="tile light"><div class="wm">${logo("wordmark.svg")}</div><figcaption>wordmark.svg — on surface</figcaption></figure>
  <figure class="tile alt"><div class="wm">${logo("wordmark.svg")}</div><figcaption>on surface-alt</figcaption></figure>
  <figure class="tile dark"><div class="wm">${logo("wordmark-inverse.svg")}</div><figcaption>wordmark-inverse.svg</figcaption></figure>
  <figure class="tile light"><div class="clear">${logo("wordmark.svg")}</div><figcaption>clear space: ½ cap height (dashed box) is the minimum</figcaption></figure>
  <figure class="tile light row"><div class="mono">${logo("monogram.svg")}</div><div class="mono">${logo("monogram-inverse.svg")}</div><div class="mono">${logo("monogram-accent.svg")}</div><div class="mono s32">${logo("monogram.svg")}</div><div class="mono s16">${logo("monogram.svg")}</div><figcaption>monogram · inverse · accent · 32 px · 16 px</figcaption></figure>
  <figure class="tile light"><div class="lk">${logo("lockup.svg")}</div><figcaption>lockup.svg</figcaption></figure>
</div>`;
}

function colourSpecimen() {
  const order = ["surface", "surface-alt", "surface-inverse", "text", "text-secondary", "border", "border-control", "accent", "accent-hover", "accent-text", "success", "warning", "danger", "sale"];
  return `<div class="spec swatches">${order
    .map((k) => {
      const hex = C[k];
      const onDark = ["surface-inverse", "text", "accent", "accent-hover", "accent-text", "success", "warning", "danger", "sale", "text-secondary", "border-control"].includes(k);
      return `<div class="sw" style="background:${hex};color:${onDark ? "#fff" : C.text}"><b>${k}</b><span>${hex}</span></div>`;
    })
    .join("")}</div>`;
}

function typeSpecimen() {
  const steps = tokens.typeScale.steps;
  const fr = JSON.parse(read("copy/strings.fr.json"));
  const ar = JSON.parse(read("copy/strings.ar.json"));
  const sample = (lang) => ({ 6: lang === "ar" ? ar["home.heroTitle"] : fr["home.heroTitle"], 4: lang === "ar" ? ar["home.featuredTitle"] : fr["home.featuredTitle"], 2: lang === "ar" ? ar["trust.cod"] : fr["trust.cod"], 0: lang === "ar" ? ar["home.heroLead"] : fr["home.heroLead"], "-1": lang === "ar" ? ar["order.phone.hint"] : fr["order.phone.hint"] });
  const rows = (lang) =>
    ["6", "4", "2", "0", "-1"]
      .map((s) => `<div class="ts" style="font-size:${Math.min(steps[s].px1440, 48)}px"><small>${s} · ${steps[s].role} · ${steps[s].px360}/${steps[s].px1440}px</small><div${lang === "ar" ? ' lang="ar" dir="rtl"' : ' lang="fr"'} class="${Number(s) >= 2 ? "hd" : ""}">${esc(sample(lang)[s])}</div></div>`)
      .join("");
  return `<div class="spec type"><div class="col"><h4>Français — system font</h4>${rows("fr")}</div><div class="col"><h4 lang="ar" dir="rtl">العربية — Noto Sans Arabic 400</h4>${rows("ar")}</div></div>`;
}

function iconSpecimen() {
  const dir = join(repo, "packages/ui-tokens/icons");
  if (!existsSync(join(dir, "manifest.json"))) return `<p class="note">Icon set: packages/ui-tokens/icons (not present in this checkout).</p>`;
  const manifest = JSON.parse(readFileSync(join(dir, "manifest.json"), "utf8"));
  const names = Object.keys(manifest.icons ?? manifest).filter((n) => existsSync(join(dir, `${n}.svg`)));
  const cell = (n, rtl) => `<figure class="ic"><span${rtl ? ' dir="rtl"' : ""}>${readFileSync(join(dir, `${n}.svg`), "utf8")}</span><figcaption>${n}</figcaption></figure>`;
  const directional = names.filter((n) => /-(start|end)$/.test(n));
  return `<div class="spec icons">${names.map((n) => cell(n, false)).join("")}</div>
<p class="note">Same four directional icons on an Arabic page (they flip; nothing else does):</p>
<div class="spec icons" dir="rtl">${directional.map((n) => cell(n, true)).join("")}</div>`;
}

// ---------------------------------------------------------------- 4. page
function fontFace() {
  const f = join(repo, "packages/ui-tokens/fonts/noto-sans-arabic-400.woff2");
  if (!existsSync(f)) return "";
  return `@font-face{font-family:"HB Noto Sans Arabic";src:url(data:font/woff2;base64,${readFileSync(f).toString("base64")}) format("woff2");font-weight:400;font-display:block}`;
}


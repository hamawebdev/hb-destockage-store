import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { expect, test } from 'vitest';
import { fixturePages } from '../src/fixtures/props.ts';

const dir = join(import.meta.dirname, '..', 'fixtures');

test.each(['ar', 'fr'] as const)('fixtures/props.%s.json is up to date', (lang) => {
  // `layout.strings` is identical on every page: stored once as `strings` to keep the file small.
  // Full props (strings included) come from `fixturePages(lang)` in '@hb/catalog/fixtures/props'.
  const pages = fixturePages(lang);
  const strings = Object.values(pages)[0]!.props.layout.strings;
  const slim = Object.fromEntries(
    Object.entries(pages).map(([path, p]) => {
      expect(p.props.layout.strings).toEqual(strings);
      return [path, { ...p, props: { ...p.props, layout: { ...p.props.layout, strings: '(see top-level strings)' } } }];
    }),
  );
  const text = JSON.stringify({ note: 'Generated by packages/catalog/test/fixtures.test.ts (UPDATE_FIXTURES=1). Do not edit.', strings, pages: slim }, null, 2) + '\n';
  const file = join(dir, `props.${lang}.json`);
  if (process.env['UPDATE_FIXTURES'] === '1') {
    mkdirSync(dir, { recursive: true });
    writeFileSync(file, text);
  }
  expect(readFileSync(file, 'utf8')).toBe(text);
});

// Pure builder: icons/*.svg -> icons/manifest.json + src/icons.generated.ts.
// Validates the icon contract so a malformed or oversized icon fails generation (and the drift test).

export const ICON_MAX_BYTES = 300;
/** Directional icons: drawn for LTR, flipped in RTL. Every other icon must not mirror. */
export const MIRRORED = ['arrow-end', 'arrow-start', 'chevron-end', 'chevron-start'] as const;
/** The rule that flips directional icons. base.css carries it; exported for other consumers. */
export const ICON_MIRROR_RULE = ':dir(rtl) [data-mirror]{transform:scaleX(-1)}';

const OPEN =
  '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"';
const INLINE_OPEN = '<svg aria-hidden="true" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"';

export interface IconFile {
  name: string;
  svg: string;
}

export interface BuiltIcon {
  /** Inline-able markup: no xmlns, aria-hidden, 24×24 default size (CSS overrides). */
  svg: string;
  mirror: boolean;
  fileBytes: number;
  inlineBytes: number;
}

export function buildIcons(files: IconFile[]): { manifest: string; ts: string; icons: Record<string, BuiltIcon> } {
  const icons: Record<string, BuiltIcon> = {};
  for (const { name, svg } of [...files].sort((a, b) => a.name.localeCompare(b.name))) {
    if (!/^[a-z][a-z0-9-]*$/.test(name)) throw new Error(`icon ${name}: name must be kebab-case`);
    if (!svg.startsWith(OPEN)) throw new Error(`icon ${name}: must start with the standard <svg …> header (24 grid, 1.5 stroke, currentColor, fill none, round caps/joins)`);
    if (!svg.endsWith('</svg>')) throw new Error(`icon ${name}: must end with </svg> (no trailing newline)`);
    const rest = svg.slice(OPEN.length);
    const mirror = rest.startsWith(' data-mirror>');
    if (!mirror && !rest.startsWith('>')) throw new Error(`icon ${name}: unexpected attributes on <svg>`);
    if (mirror !== (MIRRORED as readonly string[]).includes(name)) {
      throw new Error(`icon ${name}: data-mirror must be ${!mirror} (directional icons: ${MIRRORED.join(', ')})`);
    }
    const inner = rest.slice(rest.indexOf('>') + 1, -'</svg>'.length);
    if (!/^(<(path|circle|rect|line|polyline|polygon|ellipse) [^<>]*\/>)+$/.test(inner)) {
      throw new Error(`icon ${name}: only self-closing shape elements allowed inside <svg>`);
    }
    if (/\b(id|class|style|fill|stroke|transform|width|height)=/.test(inner.replace(/\b(cx|cy|r|rx|ry|x|y|x1|y1|x2|y2|d|points)="[^"]*"/g, ''))) {
      throw new Error(`icon ${name}: shapes may only carry geometry attributes`);
    }
    const inline = INLINE_OPEN + (mirror ? ' data-mirror>' : '>') + inner + '</svg>';
    const fileBytes = Buffer.byteLength(svg);
    const inlineBytes = Buffer.byteLength(inline);
    if (fileBytes > ICON_MAX_BYTES || inlineBytes > ICON_MAX_BYTES) {
      throw new Error(`icon ${name}: ${fileBytes} B file / ${inlineBytes} B inline > ${ICON_MAX_BYTES} B`);
    }
    icons[name] = { svg: inline, mirror, fileBytes, inlineBytes };
  }
  for (const m of MIRRORED) if (!icons[m]) throw new Error(`icon ${m} missing`);

  const manifest =
    JSON.stringify(
      {
        $description: 'GENERATED by packages/ui-tokens/src/gen/cli.ts from icons/*.svg. Do not edit.',
        grid: 24,
        stroke: 1.5,
        mirrorRule: ICON_MIRROR_RULE,
        icons: Object.fromEntries(Object.entries(icons).map(([k, v]) => [k, { mirror: v.mirror, fileBytes: v.fileBytes, inlineBytes: v.inlineBytes }])),
      },
      null,
      2,
    ) + '\n';
  const names = Object.keys(icons);
  const ts =
    `// GENERATED by packages/ui-tokens/src/gen/cli.ts from icons/*.svg. Do not edit.\n` +
    `import type { IconEntry } from './index.ts';\n\n` +
    `export type IconName = ${names.map((n) => `'${n}'`).join(' | ')};\n\n` +
    `export const ICON_MIRROR_RULE = ${JSON.stringify(ICON_MIRROR_RULE)};\n\n` +
    `export const icons: Record<IconName, IconEntry> = {\n` +
    names.map((n) => `  '${n}': { mirror: ${icons[n]!.mirror}, svg: ${JSON.stringify(icons[n]!.svg)} },`).join('\n') +
    `\n};\n`;
  return { manifest, ts, icons };
}

// Pure builder: woff2 bytes + subset.json + brand's Arabic stack -> font-face.css + src/font.generated.ts.
// unicode-range is read from the font's own cmap, so it always equals what the file can render.
import { createHash } from 'node:crypto';
import { unicodeRange, woff2CodePoints } from './woff2.ts';

export interface FontInput {
  woff2: Buffer;
  /** Path of the woff2 relative to the package root (also the url() relative to font-face.css). */
  file: string;
  /** brand font.family.arabic stack; its first family is the @font-face name. */
  arabicStack: string;
  release: string;
}

export function firstFamily(stack: string): string {
  const m = /^\s*"([^"]+)"|^\s*'([^']+)'|^\s*([^,]+)/.exec(stack);
  const name = (m?.[1] ?? m?.[2] ?? m?.[3] ?? '').trim();
  if (!name) throw new Error(`cannot read the first family of ${stack}`);
  return name;
}

export function buildFont({ woff2, file, arabicStack, release }: FontInput): { css: string; ts: string } {
  const family = firstFamily(arabicStack);
  // Control characters (NULL, CR) are never rendered; leave them out of unicode-range.
  const cps = [...woff2CodePoints(woff2)].filter((c) => c >= 0x20);
  const range = unicodeRange(cps);
  const sha256 = createHash('sha256').update(woff2).digest('hex');
  const face = {
    family,
    weight: 400,
    style: 'normal',
    display: 'optional',
    file,
    bytes: woff2.length,
    sha256,
    release,
    unicodeRange: range,
  } as const;
  const header = `GENERATED by packages/ui-tokens/src/gen/cli.ts from ${file} (${release} subset, ${woff2.length} B, sha256 ${sha256}). Do not edit.`;
  const css =
    `/* ${header}\n` +
    `   Preload on /ar/ only. Only elements whose font-family names "${family}" (--font-arabic) can fetch it. */\n` +
    `@font-face{font-family:"${family}";font-style:normal;font-weight:400;font-display:optional;` +
    `src:url("./${file}") format("woff2");unicode-range:${range}}\n`;
  const ts =
    `// ${header}\n\n` +
    `export const arabicFontFace = ${JSON.stringify(face, null, 2)} as const;\n\n` +
    `/** font-face.css as a string (url is relative to the package root). */\n` +
    `export const fontFaceCss = ${JSON.stringify(css)};\n`;
  return { css, ts };
}

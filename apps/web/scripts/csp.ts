// Post-build security headers for the static storefront (WEB-4; plan artifacts/WEB-0/plan.md §9).
// Scans the built HTML, hashes every inline <script> (incl. Speculation Rules) and <style> (SHA-256),
// and writes the Workers static-assets `_headers` file next to the HTML:
//   /*                → security headers + HTML cache policy + a fallback CSP (the not-found pages'
//                       hashes: what an unknown URL is answered with)
//   per template/lang → `! Content-Security-Policy` + its own exact CSP (hashes of its pages only;
//                       Turnstile's origin only where the order form is)
//   hashed assets     → immutable caching
// Hash-based, no nonces, no 'unsafe-inline'. Fails the build on anything that cannot be covered by
// a hash (style= attributes, inline event handlers, javascript: URLs, cross-origin scripts) and on
// the platform's limits (100 rules, 2,000 characters per line).
//
// Usage: node scripts/csp.ts [distDir]   (default ../storefront/dist; Node ≥ 24 strips the types)
// Run by wrangler's build step (wrangler.jsonc "build.command").

import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export const TURNSTILE_ORIGIN = 'https://challenges.cloudflare.com';
/** Meta's Pixel (D-009), only on pages whose <body> carries data-meta-pixel. */
export const META_SCRIPT_ORIGIN = 'https://connect.facebook.net';
export const META_PIXEL_ORIGIN = 'https://www.facebook.com';
export const MAX_RULES = 100;
export const MAX_LINE = 2000;
export const HEADER_MARK = '# Generated by apps/web/scripts/csp.ts (WEB-4). Do not edit: rebuilt on every build.';

/** Headers on every response (pages and assets). */
export const SECURITY_HEADERS: readonly (readonly [string, string])[] = [
  ['Strict-Transport-Security', 'max-age=31536000; includeSubDomains'],
  ['X-Content-Type-Options', 'nosniff'],
  ['Referrer-Policy', 'strict-origin-when-cross-origin'],
  ['Permissions-Policy', 'camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()'],
  ['Cross-Origin-Opener-Policy', 'same-origin'],
];
export const HTML_CACHE = 'public, max-age=0, must-revalidate';
export const IMMUTABLE = 'public, max-age=31536000, immutable';
/**
 * ORDER-STEP plan §4: the product page prerenders the bare `/{lang}/order/<slug>/`; a click on
 * `…/?v=<variant>` must activate that prerender. Not on the confirmation or review pages.
 */
export const NO_VARY_SEARCH = 'params=("v")';
export const ORDER_STEP_PATHS = ['/ar/order/*', '/fr/order/*'] as const;
export const ORDER_STEP_EXCLUDED = ['/ar/order/confirmation/*', '/ar/order/review/*', '/fr/order/confirmation/*', '/fr/order/review/*'] as const;
/** Content-hashed (or `?v=<hash>`-referenced) asset directories. */
export const IMMUTABLE_PATHS = ['/_astro/*', '/img/*', '/fonts/*', '/js/*'] as const;

export class CspError extends Error {
  override readonly name = 'CspError';
}

// --- HTML scanning --------------------------------------------------------------------------------

export interface PageScan {
  /** URL path the page is served at (`/ar/p/x/` for `ar/p/x/index.html`, `/ar/404.html`). */
  readonly path: string;
  readonly lang: string;
  readonly template: string;
  readonly scriptHashes: readonly string[];
  readonly styleHashes: readonly string[];
  readonly hasOrderForm: boolean;
  /** `<body data-meta-pixel>`: the page takes part in Meta tracking. */
  readonly hasMeta: boolean;
  readonly problems: readonly string[];
}

const ATTRS = `(?:[^>"']|"[^"]*"|'[^']*')*`;
const TAG_RE = new RegExp(`<(!--|script|style|[a-zA-Z][a-zA-Z0-9-]*)(${ATTRS})>`, 'gi');

export function sha256(text: string): string {
  return `'sha256-${createHash('sha256').update(text, 'utf8').digest('base64')}'`;
}

function attr(attrs: string, name: string): string | undefined {
  const m = new RegExp(`(?:^|\\s)${name}\\s*=\\s*(?:"([^"]*)"|'([^']*)'|([^\\s"'>]+))`, 'i').exec(attrs);
  return m === null ? undefined : (m[1] ?? m[2] ?? m[3] ?? '');
}

/** Script types the browser executes as script (and that CSP script-src therefore governs). */
function isExecutable(type: string | undefined): boolean {
  if (type === undefined || type.trim() === '') return true;
  const t = type.trim().toLowerCase();
  return t === 'module' || t === 'speculationrules' || t === 'text/javascript' || t === 'application/javascript' || t === 'importmap';
}

/**
 * Scans one HTML document like the HTML tokenizer does for our output: comments are skipped,
 * `<script>`/`<style>` content ends at the first `</script`/`</style` (case-insensitive).
 */
export function scanHtml(html: string, path: string): PageScan {
  const scripts = new Set<string>();
  const styles = new Set<string>();
  const problems: string[] = [];
  let lang = '';
  let template = '';
  let hasMeta = false;
  TAG_RE.lastIndex = 0;
  for (let m = TAG_RE.exec(html); m !== null; m = TAG_RE.exec(html)) {
    const name = m[1]!.toLowerCase();
    const attrs = m[2] ?? '';
    const end = TAG_RE.lastIndex;
    if (name === '!--') {
      const close = html.indexOf('-->', m.index + 4);
      TAG_RE.lastIndex = close === -1 ? html.length : close + 3;
      continue;
    }
    if (/(?:^|\s)style\s*=/i.test(attrs)) problems.push(`style= attribute on <${name}>`);
    const handler = /(?:^|\s)(on[a-z]+)\s*=/i.exec(attrs);
    if (handler !== null) problems.push(`inline event handler ${handler[1]} on <${name}>`);
    for (const a of ['href', 'src', 'action', 'formaction']) {
      if (/^\s*javascript:/i.test(attr(attrs, a) ?? '')) problems.push(`javascript: URL in ${a} on <${name}>`);
    }
    if (name === 'html') {
      lang = attr(attrs, 'lang') ?? '';
      template = attr(attrs, 'data-tpl') ?? '';
    }
    if (name === 'body' && attr(attrs, 'data-meta-pixel') !== undefined) hasMeta = true;
    if (name === 'script' || name === 'style') {
      const closeRe = new RegExp(`</${name}`, 'ig');
      closeRe.lastIndex = end;
      const close = closeRe.exec(html);
      const body = html.slice(end, close === null ? html.length : close.index);
      const after = close === null ? html.length : html.indexOf('>', close.index) + 1;
      TAG_RE.lastIndex = after;
      if (name === 'style') {
        styles.add(sha256(body));
        continue;
      }
      const src = attr(attrs, 'src');
      if (src !== undefined) {
        if (/^(?:[a-z][a-z0-9+.-]*:)?\/\//i.test(src)) problems.push(`cross-origin script src ${src}`);
        if (body.trim() !== '') problems.push('script with both src and inline content');
        continue;
      }
      if (isExecutable(attr(attrs, 'type'))) scripts.add(sha256(body));
    }
  }
  const hasOrderForm = /<form\b[^>]*\baction\s*=\s*["']?\/api\/order\b/i.test(html);
  return { path, lang, template, scriptHashes: [...scripts].sort(), styleHashes: [...styles].sort(), hasOrderForm, hasMeta, problems };
}

// --- Policy ---------------------------------------------------------------------------------------

export function buildCsp(scriptHashes: Iterable<string>, styleHashes: Iterable<string>, turnstile: boolean, meta = false): string {
  const scripts = [...new Set(scriptHashes)].sort();
  const styles = [...new Set(styleHashes)].sort();
  const d = [
    "default-src 'none'",
    `script-src 'self'${scripts.length ? ` ${scripts.join(' ')}` : ''}${turnstile ? ` ${TURNSTILE_ORIGIN}` : ''}${meta ? ` ${META_SCRIPT_ORIGIN}` : ''}`,
    // No inline style may run unless hashed; 'none' when a page has no <style> at all.
    `style-src ${styles.length ? styles.join(' ') : "'none'"}`,
    `img-src 'self'${meta ? ` ${META_PIXEL_ORIGIN}` : ''}`,
    "font-src 'self'",
    `connect-src 'self'${meta ? ` ${META_PIXEL_ORIGIN}` : ''}`,
    "manifest-src 'self'",
    "form-action 'self'",
    "base-uri 'none'",
    "object-src 'none'",
    "frame-ancestors 'none'",
  ];
  if (turnstile) d.push(`frame-src ${TURNSTILE_ORIGIN}`);
  return d.join('; ');
}

// --- Grouping pages into `_headers` rules ---------------------------------------------------------

export interface Rule {
  readonly pattern: string;
  readonly headers: readonly (readonly [string, string])[];
  /** Header names this rule detaches from earlier matching rules. */
  readonly detach?: readonly string[];
}

/** `_headers` URL pattern matching (one `*` splat, `:placeholder` segments), as the docs describe. */
export function patternMatches(pattern: string, path: string): boolean {
  const re = pattern
    .split('*')
    .map((part) => part.replace(/[.+?^${}()|[\]\\]/g, '\\$&').replace(/:[A-Za-z0-9_]+/g, '[^/]+'))
    .join('.*');
  return new RegExp(`^${re}$`).test(path);
}

function commonDirPrefix(paths: readonly string[]): string {
  let prefix = paths[0] ?? '/';
  for (const p of paths) while (!p.startsWith(prefix)) prefix = prefix.slice(0, prefix.lastIndexOf('/', prefix.length - 2) + 1);
  return prefix;
}

export interface Group {
  readonly key: string;
  readonly patterns: readonly string[];
  /** True when the group is one `<dir>*` rule (constant rule count however many pages it has). */
  readonly wildcard: boolean;
  readonly csp: string;
  readonly pages: readonly string[];
  readonly styleHashes: number;
}

/** (lang, template), split further when only some of a template's pages carry the Pixel (review vs confirmation). */
function groupKey(p: PageScan): string {
  return `${p.lang}:${p.template}${p.hasMeta ? ':meta' : ''}`;
}

function isNotFound(p: PageScan): boolean {
  return p.template === '404' || p.template === 'not-found' || /(^|\/)404\.html$/.test(p.path);
}

/** Path depth of a wildcard prefix: `/ar/p/` = 2. A wildcard needs ≥ 2 (never `/*` or `/{lang}/*`). */
function depth(prefix: string): number {
  return prefix.split('/').filter((x) => x !== '').length;
}

/**
 * Which group's CSP a path ends up with: Workers static assets apply every matching rule in file
 * order and each group rule detaches the CSP set before it, so **the last matching group rule wins**.
 */
export function effectiveGroup(groups: readonly Group[], path: string): Group | undefined {
  let owner: Group | undefined;
  for (const g of orderGroups(groups)) for (const pat of rulePatterns(g)) if (patternMatches(pat, path)) owner = g;
  return owner;
}

/** Emission order: wildcard groups broad → narrow (ties: larger first), then every exact rule. */
function orderGroups(groups: readonly Group[]): Group[] {
  const wild = groups.filter((g) => g.wildcard).sort((a, b) => a.patterns[0]!.length - b.patterns[0]!.length || b.pages.length - a.pages.length || a.key.localeCompare(b.key));
  return [...wild, ...groups.filter((g) => !g.wildcard)];
}
function rulePatterns(g: Group): readonly string[] {
  return g.patterns;
}

/**
 * One group per (lang, template). A group with several pages is one `<common dir>*` rule when that
 * directory is at least two segments deep (`/ar/p/*`, `/ar/order/*`); other groups get one exact
 * rule per page. Wildcards are emitted broad → narrow and exact rules last, so a narrower or exact
 * rule overrides a wildcard for its own pages (e.g. confirmation and review inside `/ar/order/*`).
 * If a wildcard would win a page of another group, that wildcard becomes exact rules instead
 * (repeat until every page's last matching rule is its own group's). A wildcard also matches URLs
 * that do not exist; those are answered with the 404 page, so a wildcard's policy also carries the
 * not-found pages' hashes. Rule count therefore does not grow with the number of products.
 */
export function groupPages(pages: readonly PageScan[]): Group[] {
  const byKey = new Map<string, PageScan[]>();
  for (const p of pages) {
    const key = groupKey(p);
    byKey.set(key, [...(byKey.get(key) ?? []), p]);
  }
  const notFound = pages.filter(isNotFound);
  const lists = [...byKey].sort(([a], [b]) => a.localeCompare(b));
  const exact = new Set<string>();
  for (;;) {
    const groups: Group[] = lists.map(([key, list]) => {
      const paths = list.map((p) => p.path).sort();
      const prefix = commonDirPrefix(paths);
      const wildcard = paths.length > 1 && depth(prefix) >= 2 && !exact.has(key) && !list.some(isNotFound);
      const withNotFound = wildcard ? [...list, ...notFound] : list;
      return {
        key,
        wildcard,
        patterns: wildcard ? [`${prefix}*`] : paths,
        pages: paths,
        csp: buildCsp(
          withNotFound.flatMap((p) => p.scriptHashes),
          withNotFound.flatMap((p) => p.styleHashes),
          list.some((p) => p.hasOrderForm || p.template === 'product'),
          list.some((p) => p.hasMeta),
        ),
        styleHashes: new Set(list.flatMap((p) => p.styleHashes)).size,
      };
    });
    const thief = pages
      .map((p) => ({ p, owner: effectiveGroup(groups, p.path) }))
      .find(({ p, owner }) => owner === undefined || owner.key !== groupKey(p));
    if (thief === undefined) return orderGroups(groups);
    if (thief.owner === undefined || !thief.owner.wildcard) {
      throw new CspError(`${thief.p.path} cannot be given its own CSP rule (owner: ${thief.owner?.key ?? 'none'})`);
    }
    exact.add(thief.owner.key); // that wildcard takes another template's page: make it exact rules
  }
}

export function buildRules(pages: readonly PageScan[]): { rules: Rule[]; groups: Group[] } {
  const groups = groupPages(pages);
  // Unknown URLs outside every wildcard are answered with the not-found page: the fallback CSP covers those.
  const notFound = pages.filter(isNotFound);
  const fallback = buildCsp(
    notFound.flatMap((p) => p.scriptHashes),
    notFound.flatMap((p) => p.styleHashes),
    false,
  );
  const rules: Rule[] = [
    { pattern: '/*', headers: [...SECURITY_HEADERS, ['Cache-Control', HTML_CACHE], ['Content-Security-Policy', fallback]] },
    ...IMMUTABLE_PATHS.map((pattern): Rule => ({ pattern, detach: ['Cache-Control'], headers: [['Cache-Control', IMMUTABLE]] })),
    ...ORDER_STEP_PATHS.map((pattern): Rule => ({ pattern, headers: [['No-Vary-Search', NO_VARY_SEARCH]] })),
  ];
  // groups are already in emission order (wildcards broad → narrow, then exact): last match wins.
  for (const g of groups) {
    for (const pattern of g.patterns) rules.push({ pattern, detach: ['Content-Security-Policy'], headers: [['Content-Security-Policy', g.csp]] });
  }
  // Last: confirmation and review never get No-Vary-Search (a later rule detaches an earlier one's header).
  rules.push(...ORDER_STEP_EXCLUDED.map((pattern): Rule => ({ pattern, detach: ['No-Vary-Search'], headers: [] })));
  return { rules: mergeSamePattern(rules), groups };
}

/**
 * Workers static assets keep one block per URL pattern (a repeated pattern replaces the earlier
 * block, verified in workerd), so rules with the same pattern are merged into one, at the position of
 * the LAST occurrence (so "last matching rule wins" ordering is preserved).
 */
export function mergeSamePattern(rules: readonly Rule[]): Rule[] {
  const last = new Map<string, number>();
  rules.forEach((r, i) => last.set(r.pattern, i));
  const merged = new Map<string, { detach: string[]; headers: (readonly [string, string])[] }>();
  for (const r of rules) {
    const m = merged.get(r.pattern) ?? { detach: [], headers: [] };
    for (const d of r.detach ?? []) if (!m.detach.includes(d)) m.detach.push(d);
    m.headers.push(...r.headers);
    merged.set(r.pattern, m);
  }
  return rules
    .map((r, i) => ({ r, i }))
    .filter(({ r, i }) => last.get(r.pattern) === i)
    .map(({ r }) => {
      const m = merged.get(r.pattern)!;
      return m.detach.length > 0 ? { pattern: r.pattern, detach: m.detach, headers: m.headers } : { pattern: r.pattern, headers: m.headers };
    });
}

export function renderHeaders(rules: readonly Rule[]): string {
  const seen = new Set<string>();
  for (const r of rules) {
    if (seen.has(r.pattern)) throw new CspError(`duplicate _headers pattern ${r.pattern}: the platform keeps only one block per pattern`);
    seen.add(r.pattern);
  }
  if (rules.length > MAX_RULES) throw new CspError(`${rules.length} header rules > ${MAX_RULES} (Workers static assets limit)`);
  const lines = [HEADER_MARK];
  for (const r of rules) {
    lines.push(r.pattern);
    for (const name of r.detach ?? []) lines.push(`  ! ${name}`);
    for (const [k, v] of r.headers) lines.push(`  ${k}: ${v}`);
  }
  for (const l of lines) {
    if (l.length > MAX_LINE) throw new CspError(`a _headers line is ${l.length} characters > ${MAX_LINE}: ${l.slice(0, 80)}…`);
  }
  return `${lines.join('\n')}\n`;
}

// --- Files ----------------------------------------------------------------------------------------

function htmlFiles(dir: string): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...htmlFiles(full));
    else if (name.endsWith('.html')) out.push(full);
  }
  return out;
}

export function urlPathOf(dist: string, file: string): string {
  const rel = relative(dist, file).split(sep).join('/');
  if (rel === 'index.html') return '/';
  if (rel.endsWith('/index.html')) return `/${rel.slice(0, -'index.html'.length)}`;
  return `/${rel}`;
}

export interface Report {
  readonly pages: number;
  readonly rules: number;
  readonly bytes: number;
  readonly longestLine: number;
  readonly groups: readonly { key: string; pages: number; styleHashes: number; patterns: readonly string[]; cspBytes: number }[];
}

/** Scans `dist`, writes `dist/_headers`, returns a report. Throws CspError on any problem. */
export function generate(dist: string): Report {
  if (!existsSync(dist)) throw new CspError(`storefront build not found: ${dist} (run the storefront build first)`);
  const headersPath = join(dist, '_headers');
  if (existsSync(headersPath) && !readFileSync(headersPath, 'utf8').startsWith(HEADER_MARK)) {
    throw new CspError(`${headersPath} exists and was not generated by this script: _headers is owned by apps/web`);
  }
  const pages = htmlFiles(dist).map((f) => scanHtml(readFileSync(f, 'utf8'), urlPathOf(dist, f)));
  if (pages.length === 0) throw new CspError(`no HTML in ${dist}`);
  const problems = pages.flatMap((p) => p.problems.map((x) => `${p.path}: ${x}`));
  if (problems.length > 0) throw new CspError(`CSP cannot cover:\n  ${problems.join('\n  ')}`);
  const { rules, groups } = buildRules(pages);
  const text = renderHeaders(rules);
  writeFileSync(headersPath, text);
  return {
    pages: pages.length,
    rules: rules.length,
    bytes: Buffer.byteLength(text),
    longestLine: Math.max(...text.split('\n').map((l) => l.length)),
    groups: groups.map((g) => ({ key: g.key, pages: g.pages.length, styleHashes: g.styleHashes, patterns: g.patterns, cspBytes: g.csp.length })),
  };
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dist = resolve(process.argv[2] ?? join(dirname(fileURLToPath(import.meta.url)), '../../storefront/dist'));
  try {
    const r = generate(dist);
    console.log(`csp: ${r.pages} pages, ${r.rules} rules, ${r.bytes} B _headers (longest line ${r.longestLine}/${MAX_LINE})`);
    for (const g of r.groups) {
      console.log(`  ${g.key.padEnd(18)} ${String(g.pages).padStart(4)} page(s)  ${g.styleHashes} style hash(es)  CSP ${g.cspBytes} B  ${g.patterns.length > 3 ? `${g.patterns.length} exact rules` : g.patterns.join(' ')}`);
    }
  } catch (err) {
    console.error(err instanceof CspError ? `csp: ${err.message}` : err);
    process.exit(1);
  }
}
